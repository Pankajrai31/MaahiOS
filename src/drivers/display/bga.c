/* ============================================
 * BGA Register Access
 * ============================================ */
void bga_write_register(uint16_t index, uint16_t value) {
    outw(VBE_DISPI_IOPORT_INDEX, index);
    outw(VBE_DISPI_IOPORT_DATA, value);
}

uint16_t bga_read_register(uint16_t index) {
    outw(VBE_DISPI_IOPORT_INDEX, index);
    return inw(VBE_DISPI_IOPORT_DATA);
}

/* ============================================
 * BGA Detection & Initialization
 * ============================================ */
int bga_is_available(void) {
    uint16_t version = bga_read_register(VBE_DISPI_INDEX_ID);
    return (version >= VBE_DISPI_ID0 && version <= VBE_DISPI_ID5);
}

static void bga_set_video_mode(uint16_t width, uint16_t height, uint16_t bpp) {
    bga_write_register(VBE_DISPI_INDEX_ENABLE, VBE_DISPI_DISABLED);
    bga_write_register(VBE_DISPI_INDEX_XRES, width);
    bga_write_register(VBE_DISPI_INDEX_YRES, height);
    bga_write_register(VBE_DISPI_INDEX_BPP, bpp);
    bga_write_register(VBE_DISPI_INDEX_ENABLE, VBE_DISPI_ENABLED | VBE_DISPI_LFB_ENABLED);
}

uint32_t bga_get_framebuffer_addr(void) {
    for (uint8_t slot = 0; slot < 32; slot++) {
        uint32_t vendor_device = pci_config_read_dword(0, slot, 0, 0x00);
        if (vendor_device == 0x11111234) {
            uint32_t bar0 = pci_config_read_dword(0, slot, 0, 0x10);
            if (bar0 != 0 && bar0 != 0xFFFFFFFF) {
                return bar0 & 0xFFFFFFF0;
            }
        }
    }
    return 0xFD000000;  /* QEMU default */
}

uint32_t bga_get_framebuffer_size(void) {
    return screen_width * screen_height * (screen_bpp / 8);
}

uint16_t bga_get_width(void) { return screen_width; }
uint16_t bga_get_height(void) { return screen_height; }

int bga_init(uint16_t width, uint16_t height, uint16_t bpp) {
    KLOG_INFO("BGA", "Initializing BGA hardware driver");
    
    if (!bga_is_available()) {
        KLOG_ERROR("BGA", "BGA hardware not available");
        return -1;
    }
    
    bga_set_video_mode(width, height, bpp);
    
    screen_width = bga_read_register(VBE_DISPI_INDEX_XRES);
    screen_height = bga_read_register(VBE_DISPI_INDEX_YRES);
    screen_bpp = bga_read_register(VBE_DISPI_INDEX_BPP);
    framebuffer = (uint32_t *)bga_get_framebuffer_addr();
    
    KLOG_INFO("BGA", "Mode set, framebuffer mapped");
    return 0;
}

/* ============================================
 * Drawing Functions
 * ============================================ */
void bga_clear(uint32_t color) {
    if (!framebuffer) return;
    uint32_t rgb = color & 0x00FFFFFF;
    uint32_t pixels = screen_width * screen_height;
    for (uint32_t i = 0; i < pixels; i++) {
        framebuffer[i] = rgb;
    }
}

static void bga_putchar(int x, int y, char c, uint32_t fg, uint32_t bg) {
    if (!framebuffer) return;
    if (x < 0 || y < 0 || x + 8 > screen_width || y + 16 > screen_height) return;
    
    uint8_t uc = (uint8_t)c;
    if (uc >= 128) uc = 0;
    const uint8_t *glyph = font_8x16[uc];
    
    for (int row = 0; row < 16; row++) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint32_t color = (line & (0x80 >> col)) ? fg : bg;
            framebuffer[(y + row) * screen_width + (x + col)] = color & 0x00FFFFFF;
        }
    }
}

void bga_print_at(int x, int y, const char *str, uint32_t fg, uint32_t bg) {
    if (!framebuffer) return;
    int pos_x = x, pos_y = y;
    
    while (*str) {
        if (*str == '\n') {
            pos_x = x;
            pos_y += 16;
            str++;
            continue;
        }
        bga_putchar(pos_x, pos_y, *str, fg, bg);
        pos_x += 8;
        if (pos_x + 8 > screen_width) {
            pos_x = x;
            pos_y += 16;
        }
        str++;
    }
}

void bga_fill_rect(int x, int y, int width, int height, uint32_t color) {
    if (!framebuffer) return;
    uint32_t rgb = color & 0x00FFFFFF;
    
    for (int row = y; row < y + height && row < screen_height; row++) {
        for (int col = x; col < x + width && col < screen_width; col++) {
            if (row >= 0 && col >= 0) {
                framebuffer[row * screen_width + col] = rgb;
            }
        }
    }
}

void bga_draw_rect(int x, int y, int width, int height, uint32_t color) {
    if (!framebuffer) return;
    uint32_t rgb = color & 0x00FFFFFF;
    
    for (int col = x; col < x + width && col < screen_width; col++) {
        if (col >= 0) {
            if (y >= 0 && y < screen_height)
                framebuffer[y * screen_width + col] = rgb;
            if (y + height - 1 >= 0 && y + height - 1 < screen_height)
                framebuffer[(y + height - 1) * screen_width + col] = rgb;
        }
    }
    for (int row = y; row < y + height && row < screen_height; row++) {
        if (row >= 0) {
            if (x >= 0 && x < screen_width)
                framebuffer[row * screen_width + x] = rgb;
            if (x + width - 1 >= 0 && x + width - 1 < screen_width)
                framebuffer[row * screen_width + (x + width - 1)] = rgb;
        }
    }
}

void bga_put_pixel(int x, int y, uint32_t color) {
    if (!framebuffer) return;
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height) return;
    framebuffer[y * screen_width + x] = color & 0x00FFFFFF;
}

void bga_put_pixel_alpha(int x, int y, uint32_t color, uint8_t alpha) {
    if (!framebuffer) return;
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height) return;
    
    if (alpha == 255) {
        framebuffer[y * screen_width + x] = color & 0x00FFFFFF;
    } else if (alpha > 0) {
        uint32_t bg = framebuffer[y * screen_width + x];
        uint8_t r = (((color >> 16) & 0xFF) * alpha + ((bg >> 16) & 0xFF) * (255 - alpha)) / 255;
        uint8_t g = (((color >> 8) & 0xFF) * alpha + ((bg >> 8) & 0xFF) * (255 - alpha)) / 255;
        uint8_t b = ((color & 0xFF) * alpha + (bg & 0xFF) * (255 - alpha)) / 255;
        framebuffer[y * screen_width + x] = (r << 16) | (g << 8) | b;
    }
}
