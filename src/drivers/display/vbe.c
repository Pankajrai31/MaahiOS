/**
 * MaahiOS VBE (VESA BIOS Extensions) Framebuffer Driver
 *
 * Uses the linear framebuffer that GRUB set up via the multiboot
 * VIDEO_MODE flag.  No hardware-specific I/O — just reads the
 * framebuffer address, width, height, and bpp that boot.s stored
 * in the global `vbe_mode_info` structure.
 *
 * Works on: Hyper-V Gen1, VirtualBox, QEMU, real VESA hardware.
 */

#include "vbe.h"
#include "../../managers/klog/klog.h"

/* ============================================
 * Framebuffer info populated by boot.s
 * ============================================ */
