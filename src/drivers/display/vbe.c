/* ============================================
 * Detection & Initialization
 * ============================================ */

int vbe_is_available(void) {
    /* GRUB fills vbe_mode_info if it set up a framebuffer.
     * If framebuffer_addr is 0 and width is 0, nothing was set up. */
    return (vbe_mode_info.framebuffer_addr != 0 &&
            vbe_mode_info.width != 0 &&
            vbe_mode_info.height != 0);
}

int vbe_init(void) {
    KLOG_INFO("VBE", "Initializing VBE framebuffer driver");

    if (!vbe_is_available()) {
        KLOG_ERROR("VBE", "No GRUB framebuffer info available");
        return -1;
    }

    framebuffer   = (uint32_t *)vbe_mode_info.framebuffer_addr;
    screen_width  = (uint16_t)vbe_mode_info.width;
    screen_height = (uint16_t)vbe_mode_info.height;
    screen_pitch  = vbe_mode_info.pitch;

    KLOG_INFO("VBE", "VBE framebuffer active");
    return 0;
}

/* ============================================
 * Query Functions
 * ============================================ */

uint32_t vbe_get_framebuffer_addr(void) {
    if (framebuffer)
        return (uint32_t)framebuffer;
    /* Before vbe_init(), read directly from boot.s-populated struct */
    return vbe_mode_info.framebuffer_addr;
}

uint16_t vbe_get_width(void)  { return screen_width; }
uint16_t vbe_get_height(void) { return screen_height; }

/* ============================================
 * Drawing Functions
 * ============================================ */

void vbe_clear(uint32_t color) {
    if (!framebuffer) return;
    uint32_t rgb = color & 0x00FFFFFF;
    uint32_t pixels = screen_width * screen_height;
    for (uint32_t i = 0; i < pixels; i++) {
        framebuffer[i] = rgb;
    }
}

static void vbe_putchar(int x, int y, char c, uint32_t fg, uint32_t bg) {
    if (!framebuffer) return;
    if (x < 0 || y < 0 || x + 8 > screen_width || y + 16 > screen_height) return;

    uint8_t uc = (uint8_t)c;
    if (uc >= 128) uc = 0;
    const uint8_t *glyph = font_8x16[uc];

    for (int row = 0; row < 16; row++) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint32_t color = (line & (0x80 >> col)) ? fg : bg;
            framebuffer[(y + row) * screen_width + (x + col)] = color & 0x00FFFFFF;
        }
    }
}

void vbe_print_at(int x, int y, const char *str, uint32_t fg, uint32_t bg) {
    if (!framebuffer) return;
    int pos_x = x, pos_y = y;

    while (*str) {
        if (*str == '\n') {
            pos_x = x;
            pos_y += 16;
            str++;
            continue;
        }
        vbe_putchar(pos_x, pos_y, *str, fg, bg);
        pos_x += 8;
        if (pos_x + 8 > screen_width) {
            pos_x = x;
            pos_y += 16;
        }
        str++;
    }
}

void vbe_fill_rect(int x, int y, int width, int height, uint32_t color) {
    if (!framebuffer) return;
    uint32_t rgb = color & 0x00FFFFFF;

    for (int row = y; row < y + height && row < screen_height; row++) {
        for (int col = x; col < x + width && col < screen_width; col++) {
            if (row >= 0 && col >= 0) {
                framebuffer[row * screen_width + col] = rgb;
            }
        }
    }
}

void vbe_draw_rect(int x, int y, int width, int height, uint32_t color) {
    if (!framebuffer) return;
    uint32_t rgb = color & 0x00FFFFFF;

    for (int col = x; col < x + width && col < screen_width; col++) {
        if (col >= 0) {
            if (y >= 0 && y < screen_height)
                framebuffer[y * screen_width + col] = rgb;
            if (y + height - 1 >= 0 && y + height - 1 < screen_height)
                framebuffer[(y + height - 1) * screen_width + col] = rgb;
        }
    }
    for (int row = y; row < y + height && row < screen_height; row++) {
        if (row >= 0) {
            if (x >= 0 && x < screen_width)
                framebuffer[row * screen_width + x] = rgb;
            if (x + width - 1 >= 0 && x + width - 1 < screen_width)
                framebuffer[row * screen_width + (x + width - 1)] = rgb;
        }
    }
}

void vbe_put_pixel(int x, int y, uint32_t color) {
    if (!framebuffer) return;
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height) return;
    framebuffer[y * screen_width + x] = color & 0x00FFFFFF;
}

void vbe_put_pixel_alpha(int x, int y, uint32_t color, uint8_t alpha) {
    if (!framebuffer) return;
    if (x < 0 || x >= screen_width || y < 0 || y >= screen_height) return;

    if (alpha == 255) {
        framebuffer[y * screen_width + x] = color & 0x00FFFFFF;
    } else if (alpha > 0) {
        uint32_t bg = framebuffer[y * screen_width + x];
        uint8_t r = (((color >> 16) & 0xFF) * alpha + ((bg >> 16) & 0xFF) * (255 - alpha)) / 255;
        uint8_t g = (((color >> 8) & 0xFF) * alpha + ((bg >> 8) & 0xFF) * (255 - alpha)) / 255;
        uint8_t b = ((color & 0xFF) * alpha + (bg & 0xFF) * (255 - alpha)) / 255;
        framebuffer[y * screen_width + x] = (r << 16) | (g << 8) | b;
    }
}
